#!/usr/bin/env python3
"""Generate compact simple-uppercase ranges from UnicodeData.txt (UCD 15.1).

Usage: python3 scripts/generate_unicode.py /path/to/UnicodeData.txt
The checked-in header means normal builds do not need the Unicode database.
Unicode data: https://www.unicode.org/Public/15.1.0/ucd/UnicodeData.txt
Terms: https://www.unicode.org/license.txt
"""
from pathlib import Path
import sys

pairs = []
for line in Path(sys.argv[1]).read_text().splitlines():
    fields = line.split(';')
    if fields[12]:
        pairs.append((int(fields[0], 16), int(fields[12], 16)))
ranges = []
i = 0
while i < len(pairs):
    first, upper = pairs[i]
    delta = upper - first
    j = i + 1
    stride = pairs[j][0] - first if j < len(pairs) and pairs[j][1] - pairs[j][0] == delta else 1
    if stride > 2:
        stride = 1
    while j < len(pairs) and pairs[j][0] - pairs[j - 1][0] == stride and pairs[j][1] - pairs[j][0] == delta:
        j += 1
    ranges.append((first, pairs[j - 1][0], delta, stride))
    i = j
text = '''/* Generated by scripts/generate_unicode.py from Unicode 15.1 UnicodeData.txt.
 * Copyright (c) 1991-2023 Unicode, Inc. All rights reserved.
 * Simple uppercase mappings; no normalization or multi-character expansion.
 * Unicode data terms: third_party/unicode/LICENSE (https://www.unicode.org/license.txt).
 * Modified from the original database into compact firmware lookup ranges. */
static const struct unicode_upper_range {
  uint16_t first,upper,span;
  uint8_t stride,plane;
} unicode_upper_ranges[] = {
'''
for first, last, delta, stride in ranges:
    assert last - first <= 65535
    assert first >> 16 == (first + delta) >> 16
    text += f'  {{0x{first & 65535:x}, 0x{(first+delta) & 65535:x}, {last-first}, {stride}, {first >> 16}}},\n'
text += '};\n'
text += '/* Legacy short aliases use CP437; VFAT Unicode names take precedence. */\n'
text += 'static const uint16_t unicode_oem437[128] = {\n'
for i in range(128, 256, 8):
    text += '  ' + ', '.join(f'0x{ord(bytes([j]).decode("cp437")):04x}' for j in range(i, i+8)) + ',\n'
text += '};\n'
target = Path(__file__).resolve().parents[1] / 'firmware/unicode_upper.h'
target.write_text(text)
print(f'Generated {len(ranges)} ranges in {target}')
