"""Independent US set-2 scan sequences for native and actual-CPU tests."""
NORMAL = "`1234567890-=qwertyuiop[]\\asdfghjkl;'zxcvbnm,./ "
SHIFTED = '~!@#$%^&*()_+QWERTYUIOP{}|ASDFGHJKL:"ZXCVBNM<>? '
SCANS = (0x0e,0x16,0x1e,0x26,0x25,0x2e,0x36,0x3d,0x3e,0x46,0x45,0x4e,0x55,
         0x15,0x1d,0x24,0x2d,0x2c,0x35,0x3c,0x43,0x44,0x4d,0x54,0x5b,0x5d,
         0x1c,0x1b,0x23,0x2b,0x34,0x33,0x3b,0x42,0x4b,0x4c,0x52,
         0x1a,0x22,0x21,0x2a,0x32,0x31,0x3a,0x41,0x49,0x4a,0x29)
assert len(NORMAL) == len(SHIFTED) == len(SCANS)


def tap(scan, extended=False):
    return bytes((0xe0, scan, 0xe0, 0xf0, scan)) if extended else bytes((scan, 0xf0, scan))


def key(c):
    control = {'\n': 0x5a, '\r': 0x5a, '\b': 0x66, '\x1b': 0x76, '\t': 0x0d}
    if c in control:
        return tap(control[c])
    if c in NORMAL:
        return tap(SCANS[NORMAL.index(c)])
    scan = SCANS[SHIFTED.index(c)]
    return bytes((0x12,)) + tap(scan) + bytes((0xf0, 0x12))


def text(s):
    return b''.join(map(key, s))


def compose(first, second, menu=False):
    return tap(0x2f if menu else 0x11, True) + key(first) + key(second)


def hex_start():
    return bytes((0x14, 0x12)) + tap(0x3c) + bytes((0xf0, 0x12, 0xf0, 0x14))


def hex_entry(code, terminator='\n'):
    return hex_start() + text(code) + key(terminator)
